/**
 * Simplified stroke skeletons for Kannada vowels, consonants, and digits.
 * Kannada letterforms are rounded/looped, often with a small circular
 * "head" mark at the top-left of the main body - reproduced here where
 * relevant. Best-effort simplified guide shapes, not exact font outlines.
 */

function headLoop(cx: number, cy: number, r = 8): Stroke {
  return arc(cx, cy, r, r, 0, 360, 8);
}

